"""Render the planted test database for Oracle from the same source.

Evaluates every column formula in Python (render_planted's .py semantics)
and emits quoted-lowercase DDL plus INSERT ALL batches, so identifiers
(and expected_verdicts.json keys) match MySQL/PostgreSQL exactly.
MySQL/PostgreSQL files are untouched.

Usage:
  python scripts/testdb/render_oracle.py > scripts/testdb/oracle_planted.sql

Load with SQL Developer (@script) or any Oracle client as the test user.
Stdlib only.
"""

import datetime
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render_planted as R

TYPEMAP = {
    "MEDIUMTEXT": "CLOB",
    "TEXT": "CLOB",
    "BLOB": "BLOB",
    "JSON": "CLOB",
}

INT_TYPES = {"INT"}


def q(name):
    return '"%s"' % name


def coltype(t):
    t = t.strip()
    pk = ""
    if t.upper().endswith("PRIMARY KEY"):
        t = t[: -len("PRIMARY KEY")].strip()
        pk = " PRIMARY KEY"
    base = t.split("(")[0].upper()
    if base in INT_TYPES:
        mapped = "NUMBER(10)"
    elif base == "DECIMAL":
        mapped = "NUMBER%s" % t[len("DECIMAL"):]
    elif base in ("VARCHAR",):
        mapped = "VARCHAR2%s" % t[len("VARCHAR"):]
    elif base == "CHAR":
        mapped = "CHAR%s" % t[len("CHAR"):]
    elif base == "DATE":
        mapped = "DATE"
    else:
        mapped = TYPEMAP.get(base, t)
    return mapped + pk


def lit(v, coltype_hint=""):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        # All planted floats are 2-decimal prices; format exactly so every
        # engine stores the identical decimal value.
        return "%.2f" % v
    if isinstance(v, tuple) and len(v) == 2 and isinstance(v[1], int):
        # dateoff marker: (base-date-string, day offset)
        d = datetime.date.fromisoformat(v[0]) + datetime.timedelta(days=v[1])
        return "DATE '%s'" % d.isoformat()
    s = str(v)
    assert "'" not in s, "unescaped quote in literal %r" % s
    if coltype_hint == "BLOB":
        return "UTL_RAW.CAST_TO_RAW('%s')" % s
    return "'%s'" % s


def ddl(t, names):
    lines = ["-- " + t.get("comment", t["name"])]
    cols = []
    for name, typ in t["cols"]:
        cols.append("  %s %s" % (q(name), coltype(typ)))
    if t.get("pk_extra"):
        import re
        chunk = t["pk_extra"].strip().rstrip(",")
        for nm in sorted(names, key=len, reverse=True):
            chunk = re.sub(r"\b%s\b" % re.escape(nm), q(nm), chunk)
        cols.append("  " + chunk)
    lines.append("CREATE TABLE %s (\n%s\n);" % (q(t["name"]), ",\n".join(cols)))
    return "\n".join(lines)


def inserts(t, rows):
    colnames = ", ".join(q(c[0]) for c in t["cols"])
    types = [c[1].split("(")[0].upper() for c in t["cols"]]
    stmts = []
    for i in range(0, len(rows), 200):
        body = "\n".join(
            "INTO %s (%s) VALUES (%s)" % (
                q(t["name"]), colnames,
                ", ".join(lit(v, types[k]) for k, v in enumerate(r)))
            for r in rows[i:i + 200])
        stmts.append("INSERT ALL\n%s\nSELECT * FROM DUAL;" % body)
    return "\n".join(stmts)


def table_rows(t):
    if t["name"] == "d_tiny":
        return [(1, "x", 10, "p", 100, "n1"), (1, "x", 20, "q", 101, "n2"),
                (2, "y", 10, "p", 102, "n3"), (2, "y", 30, "r", 103, "n4"),
                (3, "z", 10, "p", 104, "n5")]
    if t.get("literal") is not None:
        return [tuple(r) for r in t["literal"]]
    return [tuple(e.py(n) for e in t["exprs"]) for n in range(1, t["n"] + 1)]


def main():
    R.define_tables()
    L = []
    L.append("-- " + "=" * 67)
    L.append("-- DB Normalization Checker: planted-defect test database (Oracle Free, 23c)")
    L.append("-- " + "=" * 67)
    L.append("-- Load as the test user (see docs/TEST_PLAN.md), e.g. in SQL Developer:")
    L.append("--   @scripts/testdb/oracle_planted.sql")
    L.append("-- Same rows as mysql/postgres_planted.sql (evaluated from one source).")
    L.append("-- Expected verdicts: scripts/testdb/expected_verdicts.json")
    L.append("-- Generated by scripts/testdb/render_oracle.py -- do not hand-edit.")
    L.append("")
    names = [t["name"] for t in R.TABLES] + ["d_tiny"]
    name_set = set(names)
    for t in R.TABLES:
        name_set.update(c[0] for c in t["cols"])
    name_set.update(("a", "b", "c", "d", "e", "f_note"))
    for name in reversed(names):
        L.append("DROP TABLE %s IF EXISTS CASCADE CONSTRAINTS;" % q(name))
    L.append("")
    # d_tiny DDL (matches mysql/pg shape)
    L.append("-- d_tiny: 5 rows where a->b happens to hold -> insufficient_data.")
    L.append("CREATE TABLE %s (\n"
             "  %s INT, %s VARCHAR2(8), %s INT, %s VARCHAR2(8), %s INT, %s VARCHAR2(20)\n);"
             % ((q("d_tiny"),) + tuple(q(c) for c in ("a", "b", "c", "d", "e", "f_note"))))
    for t in R.TABLES:
        L.append(ddl(t, name_set))
    L.append("")
    tiny = {"name": "d_tiny",
            "cols": [("a", "INT"), ("b", "VARCHAR(8)"), ("c", "INT"),
                     ("d", "VARCHAR(8)"), ("e", "INT"), ("f_note", "VARCHAR(20)")]}
    L.append(inserts(tiny, table_rows({"name": "d_tiny"})))
    total = 5
    for t in R.TABLES:
        rows = table_rows(t)
        total += len(rows)
        L.append("-- %s: %d rows" % (t["name"], len(rows)))
        L.append(inserts(t, rows))
    L.append("")
    L.append("-- total rows: %d" % total)
    L.append("COMMIT;")
    out = OUT / "oracle_planted.sql"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote %s (%d tables, %d rows)" % (out, len(R.TABLES) + 1, total))


OUT = Path(__file__).resolve().parent


if __name__ == "__main__":
    main()
